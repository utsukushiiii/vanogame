# [исх. 9] Объявляем класс SmallGrid: описание будущих объектов.
class SmallGrid:
    # МЕТОД SmallGrid.__init__. Вспомогательная функция проверки; действия подробно разобраны ниже.
    # Параметр self: текущий объект.
    # Параметр rows: число строк сетки.
    # [исх. 10] Объявляем __init__: тело ниже выполнится при вызове. Отступы определяют, какие строки входят в
    # метод.
    def __init__(self, rows):
        # [исх. 11] В self.walkable (множество свободных навигационных клеток) записываем результат: собираем (x,
        # y) для каждого (y, row) из enumerate(rows).
        self.walkable = {(x, y) for y, row in enumerate(rows)
                         # [исх. 12] Продолжение выражения выше: кортеж из 2 элементов, перечисленных ниже в коде.
                         for x, value in enumerate(row) if value != "#"}

    # МЕТОД SmallGrid.is_walkable. Вспомогательная функция проверки; действия подробно разобраны ниже.
    # Параметр self: текущий объект.
    # Параметр cell: пара целых координат клетки.
    # [исх. 14] Объявляем is_walkable: тело ниже выполнится при вызове. Отступы определяют, какие строки входят в
    # метод.
    def is_walkable(self, cell):
        # [исх. 15] Завершаем этот вызов и возвращаем вызывающему коду: cell содержится в self.walkable.
        return cell in self.walkable

    # МЕТОД SmallGrid.neighbors. Вспомогательная функция проверки; действия подробно разобраны ниже.
    # Параметр self: текущий объект.
    # Параметр cell: пара целых координат клетки.
    # [исх. 17] Объявляем neighbors: тело ниже выполнится при вызове. Отступы определяют, какие строки входят в
    # метод.
    def neighbors(self, cell):
        # [исх. 18] Завершаем этот вызов и возвращаем вызывающему коду: создаём неизменяемую последовательность;
        # аргументы: ((cell[0] + dx, cell[1] + dy) for dx, dy in DIRECTIONS if (cell[0] + dx, cell[1] +
        # dy) in self.walkable).
        return tuple((cell[0] + dx, cell[1] + dy) for dx, dy in DIRECTIONS
                     # [исх. 19] Продолжение выражения выше: (cell[0] + dx, cell[1] + dy) содержится в
                     # self.walkable.
                     if (cell[0] + dx, cell[1] + dy) in self.walkable)


# МЕТОД bfs_cost. Вспомогательная функция проверки; действия подробно разобраны ниже.
# Параметр grid: сетка для быстрого поиска соседей или стен.
# Параметр start: начало маршрута.
# Параметр goal: целевая клетка.
# [исх. 22] Объявляем bfs_cost: тело ниже выполнится при вызове. Отступы определяют, какие строки входят в метод.
def bfs_cost(grid, start, goal):
    # [исх. 23] Проверяем: grid.is_walkable(start) ложно, равно нулю или пусто; либо grid.is_walkable(goal) ложно,
    # равно нулю или пусто. При успехе выполняется вложенный блок.
    if not grid.is_walkable(start) or not grid.is_walkable(goal):
        # [исх. 24] Завершаем этот вызов и возвращаем вызывающему коду: None — значение отсутствует.
        return None
    # [исх. 25] В queue (очередь необработанных записей) записываем результат: вызываем deque([(start, 0)]);
    # параметры названы в определении этого метода.
    queue = deque([(start, 0)])
    # [исх. 26] В visited записываем результат: множество из 1 элементов, перечисленных ниже в коде.
    visited = {start}
    # [исх. 27] Повторяем вложенный блок, пока queue имеет истинное значение (не False, не None, не ноль и не
    # пустая коллекция). Условие заново проверяется перед каждой итерацией.
    while queue:
        # [исх. 28] В (cell, distance) записываем результат: извлекаем самый старый элемент очереди слева у queue.
        cell, distance = queue.popleft()
        # [исх. 29] Проверяем: cell равно goal. При успехе выполняется вложенный блок.
        if cell == goal:
            # [исх. 30] Завершаем этот вызов и возвращаем вызывающему коду: distance (длина перемещения или
            # расстояние до цели).
            return distance
        # [исх. 31] Перебираем вызываем grid.neighbors(cell); параметры названы в определении этого метода.
        # Очередной элемент записывается в neighbor, затем выполняется вложенный блок.
        for neighbor in grid.neighbors(cell):
            # [исх. 32] Проверяем: neighbor отсутствует в visited. При успехе выполняется вложенный блок.
            if neighbor not in visited:
                # [исх. 33] Добавляем элемент в множество без повторов у visited; аргументы: neighbor.
                visited.add(neighbor)
                # [исх. 34] Добавляем один элемент в конец у queue; аргументы: (neighbor, distance + 1).
                queue.append((neighbor, distance + 1))
    # [исх. 35] Завершаем этот вызов и возвращаем вызывающему коду: None — значение отсутствует.
    return None


