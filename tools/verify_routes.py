# [исх. 27] Объявляем класс RouteController: описание будущих объектов.
class RouteController:
    # [исх. 28] Строка документации объясняет назначение модуля, класса или функции; игровые действия здесь не
    # выполняются.
    """Обратная связь управляет только кнопками, координаты мира не меняет."""

    # МЕТОД RouteController.__init__. Вспомогательная функция проверки; действия подробно разобраны
    # ниже.
    # Параметр self: текущий объект.
    # Параметр session: сеанс прохождения всей игры; ожидаемый тип GameSession.
    # [исх. 30] Объявляем __init__: тело ниже выполнится при вызове. Отступы определяют, какие строки входят в
    # метод.
    def __init__(self, session: GameSession):
        # [исх. 31] В self.session (сеанс прохождения всей игры) записываем результат: session (сеанс прохождения
        # всей игры).
        self.session = session
        # [исх. 32] В self.jumps записываем результат: число 0.
        self.jumps = 0
        # [исх. 33] В self.steps (число выполненных физических шагов) записываем результат: число 0.
        self.steps = 0

    # [исх. 35] Декоратор property: следующий метод читается как поле без скобок, например box.right.
    @property
    # МЕТОД RouteController.player. Вспомогательная функция проверки; действия подробно разобраны ниже.
    # Параметр self: текущий объект.
    # [исх. 36] Объявляем player: тело ниже выполнится при вызове. Отступы определяют, какие строки входят в
    # метод.
    def player(self):
        # [исх. 37] Завершаем этот вызов и возвращаем вызывающему коду: self.session.level.player (тело героя).
        return self.session.level.player

    # МЕТОД RouteController.tick. Вспомогательная функция проверки; действия подробно разобраны ниже.
    # Параметр self: текущий объект.
    # Параметр move: направление бега: -1, 0 или 1; ожидаемый тип int; если не передать, используется 0.
    # Параметр jump: входное значение; использование показано в строках тела; ожидаемый тип bool; если
    # не передать, используется False.
    # Параметр held: входное значение; использование показано в строках тела; ожидаемый тип bool; если
    # не передать, используется False.
    # Параметр interact: разовый запрос действия E; ожидаемый тип bool; если не передать, используется
    # False.
    # После -> указан ожидаемый тип результата: None. Это подсказка, не автоматическая проверка.
    # [исх. 39] Объявляем tick: тело ниже выполнится при вызове. Отступы определяют, какие строки входят в метод.
    def tick(self, move: int = 0, jump: bool = False, held: bool = False,
             # [исх. 40] Продолжение выражения выше: bool.
             interact: bool = False) -> None:
        # [исх. 41] В previous_deaths записываем результат: self.session.deaths (число смертей и возвратов по R).
        previous_deaths = self.session.deaths
        # [исх. 42] В previous_box записываем результат: создаём отдельную копию у self.player.box.
        previous_box = self.player.box.copy()
        # [исх. 43] В enemy_positions записываем результат: собираем (enemy.id, enemy.box.copy()) для каждого
        # enemy из self.session.level.enemies.
        enemy_positions = [(enemy.id, enemy.box.copy()) for enemy in self.session.level.enemies]
        # [исх. 44] Вызываем self.session.update(config.FIXED_DT, Commands(move, jump, held, interact)); параметры
        # названы в определении этого метода.
        self.session.update(config.FIXED_DT, Commands(move, jump, held, interact))
        # [исх. 45] Меняем self.steps (число выполненных физических шагов): прибавляем число 1 и сохраняем
        # обратно.
        self.steps += 1
        # [исх. 46] Меняем self.jumps: прибавляем суммируем значения; True считается 1, False — 0; аргументы:
        # (event.kind == 'jump' for event in self.session.drain_events()) и сохраняем обратно.
        self.jumps += sum(event.kind == 'jump' for event in self.session.drain_events())
        # [исх. 47] Проверяем: self.session.deaths не равно previous_deaths. При успехе выполняется вложенный
        # блок.
        if self.session.deaths != previous_deaths:
            # [исх. 48] Останавливаем нормальное выполнение исключением AssertionError(f'Уровень
            # {self.session.level_index + 1}, шаг {self.steps}: смерть у {previous_box}; враги
            # {enemy_positions}'). Сообщение объясняет нарушенное условие.
            raise AssertionError(f'Уровень {self.session.level_index + 1}, шаг {self.steps}: '
                                 # [исх. 49] Продолжение выражения выше: вычисляем {previous_box}.
                                 f'смерть у {previous_box}; враги {enemy_positions}')

    # МЕТОД RouteController.direction. Вспомогательная функция проверки; действия подробно разобраны
    # ниже.
    # Параметр self: текущий объект.
    # Параметр target_x: входное значение; использование показано в строках тела; ожидаемый тип float.
    # После -> указан ожидаемый тип результата: int. Это подсказка, не автоматическая проверка.
    # [исх. 51] Объявляем direction: тело ниже выполнится при вызове. Отступы определяют, какие строки входят в
    # метод.
    def direction(self, target_x: float) -> int:
        # [исх. 52] В distance (длина перемещения или расстояние до цели) записываем результат: разность в формуле
        # target_x - self.player.box.x.
        distance = target_x - self.player.box.x
        # [исх. 53] В stopping записываем результат: деление в формуле self.player.vx ** 2 / (2 * config.BRAKING).
        stopping = self.player.vx ** 2 / (2 * config.BRAKING)
        # [исх. 54] Проверяем: abs(distance) меньше 0.8. При успехе выполняется вложенный блок.
        if abs(distance) < 0.8:
            # [исх. 55] Завершаем этот вызов и возвращаем вызывающему коду: число 0.
            return 0
        # [исх. 56] Проверяем: distance * self.player.vx больше 0; одновременно abs(distance) не больше stopping +
        # 0.5. При успехе выполняется вложенный блок.
        if distance * self.player.vx > 0 and abs(distance) <= stopping + 0.5:
            # [исх. 57] Завершаем этот вызов и возвращаем вызывающему коду: число 0.
            return 0
        # [исх. 58] Завершаем этот вызов и возвращаем вызывающему коду: 1, если distance больше 0; иначе -1.
        return 1 if distance > 0 else -1

    # МЕТОД RouteController.wait_for. Вспомогательная функция проверки; действия подробно разобраны
    # ниже.
    # Параметр self: текущий объект.
    # Параметр predicate: входное значение; использование показано в строках тела; ожидаемый тип
    # Callable[[], bool].
    # Параметр limit: входное значение; использование показано в строках тела; ожидаемый тип float; если
    # не передать, используется 8.0.
    # После -> указан ожидаемый тип результата: None. Это подсказка, не автоматическая проверка.
    # [исх. 60] Объявляем wait_for: тело ниже выполнится при вызове. Отступы определяют, какие строки входят в
    # метод.
    def wait_for(self, predicate: Callable[[], bool], limit: float = 8.0) -> None:
        # [исх. 61] Перебираем целые числа range(round(limit / config.FIXED_DT)); правая граница не включается,
        # третий аргумент задаёт шаг. Очередной элемент записывается в _, затем выполняется вложенный
        # блок.
        for _ in range(round(limit / config.FIXED_DT)):
            # [исх. 62] Проверяем: predicate() имеет истинное значение (не False, не None, не ноль и не пустая
            # коллекция). При успехе выполняется вложенный блок.
            if predicate():
                # [исх. 63] Завершаем этот вызов и возвращаем вызывающему коду: None — отсутствие результата.
                return
            # [исх. 64] Вызываем self.tick(); параметры названы в определении этого метода.
            self.tick()
        # [исх. 65] Останавливаем нормальное выполнение исключением AssertionError(f'Ожидание не завершилось:
        # {self.player.box}'). Сообщение объясняет нарушенное условие.
        raise AssertionError(f'Ожидание не завершилось: {self.player.box}')

    # МЕТОД RouteController.walk. Вспомогательная функция проверки; действия подробно разобраны ниже.
    # Параметр self: текущий объект.
    # Параметр target_x: входное значение; использование показано в строках тела; ожидаемый тип float.
    # Параметр limit: входное значение; использование показано в строках тела; ожидаемый тип float; если
    # не передать, используется 8.0.
    # После -> указан ожидаемый тип результата: None. Это подсказка, не автоматическая проверка.
    # [исх. 67] Объявляем walk: тело ниже выполнится при вызове. Отступы определяют, какие строки входят в метод.
    def walk(self, target_x: float, limit: float = 8.0) -> None:
        # [исх. 68] Перебираем целые числа range(round(limit / config.FIXED_DT)); правая граница не включается,
        # третий аргумент задаёт шаг. Очередной элемент записывается в _, затем выполняется вложенный
        # блок.
        for _ in range(round(limit / config.FIXED_DT)):
            # [исх. 69] Проверяем: abs(self.player.box.x - target_x) меньше 1.5; одновременно abs(self.player.vx)
            # меньше 20. При успехе выполняется вложенный блок.
            if abs(self.player.box.x - target_x) < 1.5 and abs(self.player.vx) < 20:
                # [исх. 70] Завершаем этот вызов и возвращаем вызывающему коду: None — отсутствие результата.
                return
            # [исх. 71] Вызываем self.tick(self.direction(target_x)); параметры названы в определении этого
            # метода.
            self.tick(self.direction(target_x))
        # [исх. 72] Останавливаем нормальное выполнение исключением AssertionError(f'Не дошёл до {target_x}:
        # {self.player.box}'). Сообщение объясняет нарушенное условие.
        raise AssertionError(f'Не дошёл до {target_x}: {self.player.box}')

    # МЕТОД RouteController.jump. Вспомогательная функция проверки; действия подробно разобраны ниже.
    # Параметр self: текущий объект.
    # Параметр target_x: входное значение; использование показано в строках тела; ожидаемый тип float |
    # Callable[[], float].
    # Параметр limit: входное значение; использование показано в строках тела; ожидаемый тип float; если
    # не передать, используется 2.0.
    # После -> указан ожидаемый тип результата: None. Это подсказка, не автоматическая проверка.
    # [исх. 74] Объявляем jump: тело ниже выполнится при вызове. Отступы определяют, какие строки входят в метод.
    def jump(self, target_x: float | Callable[[], float], limit: float = 2.0) -> None:
        # [исх. 75] Проверяем: self.player.grounded ложно, равно нулю или пусто. При успехе выполняется вложенный
        # блок.
        if not self.player.grounded:
            # [исх. 76] Вызываем self.wait_for(lambda: self.player.grounded); параметры названы в определении
            # этого метода.
            self.wait_for(lambda: self.player.grounded)
        # [исх. 77] В target (целевое значение или точка назначения по контексту) записываем результат: target_x,
        # если callable(target_x) имеет истинное значение (не False, не None, не ноль и не пустая
        # коллекция); иначе lambda: target_x.
        target = target_x if callable(target_x) else lambda: target_x
        # [исх. 78] Вызываем self.tick(self.direction(target())); параметры названы в определении этого метода.
        self.tick(self.direction(target()), jump=True, held=True)
        # [исх. 79] В airborne записываем результат: логическое отрицание: self.player.grounded должно быть ложным
        # или пустым.
        airborne = not self.player.grounded
        # [исх. 80] Перебираем целые числа range(round(limit / config.FIXED_DT)); правая граница не включается,
        # третий аргумент задаёт шаг. Очередной элемент записывается в _, затем выполняется вложенный
        # блок.
        for _ in range(round(limit / config.FIXED_DT)):
            # [исх. 81] Проверяем: airborne имеет истинное значение (не False, не None, не ноль и не пустая
            # коллекция); одновременно self.player.grounded имеет истинное значение (не False, не None,
            # не ноль и не пустая коллекция). При успехе выполняется вложенный блок.
            if airborne and self.player.grounded:
                # Перед следующим нажатием действительно отпускаем кнопку.
                # Это позволяет воспроизвести маршрут через InputBuffer окна.
                # [исх. 84] Вызываем self.tick(); параметры названы в определении этого метода.
                self.tick(held=False)
                # [исх. 85] Завершаем этот вызов и возвращаем вызывающему коду: None — отсутствие результата.
                return
            # [исх. 86] Вызываем self.tick(self.direction(target())); параметры названы в определении этого
            # метода.
            self.tick(self.direction(target()), held=True)
            # [исх. 87] Меняем airborne: применяем операцию с логическое отрицание: self.player.grounded должно
            # быть ложным или пустым и сохраняем обратно.
            airborne |= not self.player.grounded
        # [исх. 88] Останавливаем нормальное выполнение исключением AssertionError(f'Прыжок не завершился:
        # {self.player.box}'). Сообщение объясняет нарушенное условие.
        raise AssertionError(f'Прыжок не завершился: {self.player.box}')

    # МЕТОД RouteController.require_page. Вспомогательная функция проверки; действия подробно разобраны
    # ниже.
    # Параметр self: текущий объект.
    # Параметр identifier: уникальное имя объекта; ожидаемый тип str.
    # После -> указан ожидаемый тип результата: None. Это подсказка, не автоматическая проверка.
    # [исх. 90] Объявляем require_page: тело ниже выполнится при вызове. Отступы определяют, какие строки входят в
    # метод.
    def require_page(self, identifier: str) -> None:
        # [исх. 91] В item (один предмет уровня) записываем результат: берём следующий или первый подходящий
        # элемент итератора; аргументы: (page for page in self.session.level.pages if page.id ==
        # identifier).
        item = next(page for page in self.session.level.pages if page.id == identifier)
        # [исх. 92] Проверяем: item.collected ложно, равно нулю или пусто. При успехе выполняется вложенный блок.
        if not item.collected:
            # [исх. 93] Останавливаем нормальное выполнение исключением AssertionError(f'Не подобрана
            # {identifier}: {self.player.box}'). Сообщение объясняет нарушенное условие.
            raise AssertionError(f'Не подобрана {identifier}: {self.player.box}')


